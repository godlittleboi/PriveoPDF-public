"""One fixed operation: cap the connecting process, identified by a kernel PIDFD.

Runs without network, documents or desktop sockets. Only this separate helper
can reach the user manager. No request body, PID, command or limit is accepted.
"""

from __future__ import annotations

import argparse
import ctypes
import os
import select
import signal
import socket
import struct
import sys
import uuid
from contextlib import suppress
from pathlib import Path

MEMORY_BYTES = 1536 * 1024**2
SO_PEERPIDFD = 77  # Linux 6.5+, including Mint's 6.8 kernel
BROKER_ENV = "PRIVEOPDF_RENDER_BROKER_SOCKET"
_SOCKET = "/run/priveopdf-memory/memory.sock"
_BUS = "/run/priveopdf-manager/bus"
_MAX_ACTIVE = 4


def _create_scope(pidfd: int, memory_bytes: int = MEMORY_BYTES) -> str:
    """Send only fixed properties and the peer PIDFD (systemd >= 255)."""
    name = "priveopdf-render-" + uuid.uuid4().hex + ".scope"
    _scope_operation(name, pidfd, memory_bytes)
    return name


def _stop_scope(name: str) -> None:
    """Stop a scope generated by this helper, including across PID namespaces."""
    _scope_operation(name, None, 0)


def _scope_operation(scope_name: str, pidfd: int | None, memory_bytes: int) -> None:
    lib = ctypes.CDLL("libsystemd.so.0")
    ptr = ctypes.c_void_p
    signatures = {
        "sd_bus_open_user": [ctypes.POINTER(ptr)],
        "sd_bus_message_new_method_call": [ptr, ctypes.POINTER(ptr), *([ctypes.c_char_p] * 4)],
        "sd_bus_message_open_container": [ptr, ctypes.c_char, ctypes.c_char_p],
        "sd_bus_message_close_container": [ptr],
        "sd_bus_message_append_basic": [ptr, ctypes.c_char, ptr],
        "sd_bus_call": [ptr, ptr, ctypes.c_uint64, ptr, ctypes.POINTER(ptr)],
        "sd_bus_message_unref": [ptr],
        "sd_bus_unref": [ptr],
    }
    for name, args in signatures.items():
        getattr(lib, name).argtypes = args
        getattr(lib, name).restype = ptr if name.endswith("unref") else ctypes.c_int

    def checked(name, *args):
        result = getattr(lib, name)(*args)
        if result < 0:
            raise OSError(-result, "render scope unavailable")

    bus, message, reply = ptr(), ptr(), ptr()
    try:
        checked("sd_bus_open_user", ctypes.byref(bus))
        checked(
            "sd_bus_message_new_method_call",
            bus,
            ctypes.byref(message),
            b"org.freedesktop.systemd1",
            b"/org/freedesktop/systemd1",
            b"org.freedesktop.systemd1.Manager",
            b"StartTransientUnit" if pidfd is not None else b"StopUnit",
        )

        def basic(kind, value):
            if kind == b"s":
                data = ctypes.c_char_p(value.encode())
            else:
                data = ctypes.byref((ctypes.c_uint64 if kind == b"t" else ctypes.c_int)(value))
            checked("sd_bus_message_append_basic", message, kind, data)

        def open_container(kind, contents):
            checked("sd_bus_message_open_container", message, kind, contents)

        def close_container():
            checked("sd_bus_message_close_container", message)

        basic(b"s", scope_name)
        basic(b"s", "fail" if pidfd is not None else "replace")
        if pidfd is not None:
            open_container(b"a", b"(sv)")
            for name, kind, value in (
                ("Description", b"s", "PriveoPDF local render"),
                ("CollectMode", b"s", "inactive-or-failed"),
                ("MemoryMax", b"t", memory_bytes),
                ("MemorySwapMax", b"t", 0),
                # systemd derives memory.oom.group from OOMPolicy at scope load;
                # MemoryOOMGroup alone is overwritten by the manager default.
                ("OOMPolicy", b"s", "kill"),
                ("TasksMax", b"t", 64),
                ("PIDFDs", b"ah", pidfd),
            ):
                open_container(b"r", b"sv")
                basic(b"s", name)
                open_container(b"v", kind)
                if kind == b"ah":
                    open_container(b"a", b"h")
                    basic(b"h", value)
                    close_container()
                else:
                    basic(kind, value)
                close_container()
                close_container()
            close_container()
            open_container(b"a", b"(sa(sv))")
            close_container()
        checked("sd_bus_call", bus, message, 3_000_000, None, ctypes.byref(reply))
    finally:
        lib.sd_bus_message_unref(reply)
        lib.sd_bus_message_unref(message)
        lib.sd_bus_unref(bus)


def _register_peer(peer: socket.socket, active: list[tuple[int, str]]) -> None:
    for fd, name in list(active):
        if select.select([fd], [], [], 0)[0]:
            active.remove((fd, name))
            os.close(fd)
    _pid, uid, _gid = struct.unpack(
        "3i", peer.getsockopt(socket.SOL_SOCKET, socket.SO_PEERCRED, 12)
    )
    if uid != os.getuid() or len(active) >= _MAX_ACTIVE:
        raise OSError("render peer refused")
    # Derived by the kernel from this socket, never supplied by the client.
    fd = peer.getsockopt(socket.SOL_SOCKET, SO_PEERPIDFD)
    os.set_inheritable(fd, False)
    try:
        name = _create_scope(fd)
    except BaseException:
        os.close(fd)
        raise
    active.append((fd, name))


def serve(endpoint: str = _SOCKET) -> None:
    active: list[tuple[int, str]] = []

    def stop(_signum, _frame):
        raise SystemExit(0)

    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)
    try:
        with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as server:
            server.bind(endpoint)
            server.listen(4)
            while True:
                peer, _ = server.accept()
                with peer:
                    peer.settimeout(3)
                    try:
                        _register_peer(peer, active)
                        peer.sendall(b"1")
                    except OSError:
                        # No peer data or raw systemd error is read, echoed or logged.
                        with suppress(OSError):
                            peer.sendall(b"0")
    finally:
        for fd, name in active:
            with suppress(OSError):
                _stop_scope(name)
            os.close(fd)


def broker_command(endpoint: Path) -> tuple[str, ...]:
    from priveopdf.workers.local_confinement import _runtime_read_roots

    command = [
        "/usr/bin/bwrap",
        "--die-with-parent",
        "--new-session",
        "--unshare-net",
        "--unshare-ipc",
        "--unshare-pid",
        "--proc",
        "/proc",
        "--unshare-uts",
        "--dev",
        "/dev",
        "--tmpfs",
        "/tmp",  # noqa: S108 - private tmpfs in the helper namespace
        "--dir",
        "/run/priveopdf-manager",
        "--ro-bind",
        f"/run/user/{os.getuid()}/bus",
        _BUS,
        "--bind",
        str(endpoint.parent),
        "/run/priveopdf-memory",
        "--clearenv",
        "--setenv",
        "PATH",
        "/usr/bin:/bin",
        "--setenv",
        "DBUS_SESSION_BUS_ADDRESS",
        "unix:path=" + _BUS,
        "--setenv",
        "XDG_RUNTIME_DIR",
        "/run/priveopdf-manager",
        "--setenv",
        "TMPDIR",
        "/tmp",  # noqa: S108 - private tmpfs in the helper namespace
    ]
    for path in _runtime_read_roots():
        command.extend(("--ro-bind", str(path), str(path)))
    if getattr(sys, "frozen", False):
        worker = (sys.executable, "--render-memory-broker", "--serve")
    else:
        command.extend(("--setenv", "PYTHONPATH", str(Path(__file__).resolve().parents[2])))
        worker = (sys.executable, "-P", "-m", "priveopdf.workers.render_memory_broker", "--serve")
    return (*command, "--", *worker)


def main(argv=None) -> int:
    os.umask(0o077)
    parser = argparse.ArgumentParser(allow_abbrev=False)
    parser.add_argument("--socket", type=Path)
    parser.add_argument("--serve", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.serve:
            serve()
        elif args.socket and args.socket.name == "memory.sock":
            command = broker_command(args.socket.resolve())
            os.execv(command[0], command)  # noqa: S606 - fixed helper sandbox arguments
        else:
            return 78
    except (OSError, ValueError):
        return 78
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
